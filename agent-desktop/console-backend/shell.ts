// console-backend C1 — browser shell: static SPA serving + hermesAPI
// shim download.
//
// The doctrine's kernel/shell split (§3): same kernel, many shells.
// The Electron renderer's sources are built by the existing Vite
// pipeline (electron-vite build → out/renderer); this module serves
// that build at / and hands the renderer its transport shim, so the
// EXACT same 27 screens run in a browser instead of an Electron
// window. The shim is generated from the route registry, so it can
// never drift from the kernel's capabilities (parity enforced in
// both directions).

import { createReadStream, existsSync, readFileSync, statSync } from "fs";
import { extname, join, normalize } from "path";

const MIME: Record<string, string> = {
  ".html": "text/html; charset=utf-8",
  ".js": "application/javascript; charset=utf-8",
  ".mjs": "application/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".json": "application/json; charset=utf-8",
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".ico": "image/x-icon",
  ".woff": "font/woff",
  ".woff2": "font/woff2",
  ".map": "application/json",
};

/** Serve the built renderer (out/renderer) with SPA fallback to
 *  index.html. The HTML response gets the /shim.js script injected
 *  BEFORE the bundle (the browser shell's contextBridge analog must
 *  exist before renderer code runs). Returns false when the request
 *  is not a static-asset request (caller continues API routing). */
export function serveRenderer(
  req: { method?: string; url?: string },
  res: {
    setHeader: (k: string, v: string) => void;
    write: (b: string) => unknown;
    end: (b?: unknown) => void;
    statusCode: number;
  },
  rendererRoot: string,
): boolean {
  if (req.method !== "GET" && req.method !== "HEAD") return false;
  const url = new URL(req.url ?? "/", "http://127.0.0.1");
  if (url.pathname.startsWith("/api/") || url.pathname === "/health" || url.pathname === "/shim.js") return false;

  const rel = url.pathname === "/" ? "index.html" : url.pathname.replace(/^\/+/, "");
  const candidate = normalize(join(rendererRoot, rel));
  if (!candidate.startsWith(rendererRoot)) {
    res.statusCode = 403;
    res.end(JSON.stringify({ success: false, error: "forbidden" }));
    return true;
  }
  const fileExists = existsSync(candidate) && statSync(candidate).isFile();
  const target = fileExists ? candidate : existsSync(join(rendererRoot, "index.html")) ? join(rendererRoot, "index.html") : null;
  if (target === null) {
    res.statusCode = 404;
    res.end(JSON.stringify({ success: false, error: "renderer not built (run electron-vite build)" }));
    return true;
  }
  if (target.endsWith(".html")) {
    // Inject the shim before the first module script so window.hermesAPI
    // exists before the renderer bundle executes (contextBridge analog).
    const html = readFileSync(target, "utf8");
    const patched = html.replace(
      /(<script[^>]*type="module"[^>]*>)/i,
      '<script src="/shim.js"></script>$1',
    );
    res.setHeader("content-type", "text/html; charset=utf-8");
    res.end(patched);
    return true;
  }
  res.setHeader("content-type", MIME[extname(target).toLowerCase()] ?? "application/octet-stream");
  createReadStream(target).pipe(res as never);
  return true;
}

/** Generate the browser shim: window.hermesAPI + window.electron with
 *  the EXACT method surface of the desktop preload — seeded methods
 *  invoke the kernel over HTTP; every other bridge method degrades to
 *  a stable no-op result (the desktop's never-throws convention), so
 *  partial kernel coverage never crashes the renderer while the port
 *  catches up. The renderer code is unchanged — it calls
 *  window.hermesAPI.x(...) and gets a Promise, exactly like the
 *  contextBridge version. */
export function renderShimJs(
  registry: { list: () => Array<{ name: string; ipcChannel: string }> },
): string {
  const methods = registry
    .list()
    .map(
      (r) =>
        `  ${r.name}: (...args) => kernelInvoke("${r.name}", args),`,
    )
    .join("\n");
  return `// Generated by console-backend/shell.ts — do not edit by hand.
// Browser transport shim: window.hermesAPI calls the kernel over HTTP
// instead of Electron IPC. Kernel-seeded methods (${registry.list().length}) transport
// as POST /api/console/<name>; UNSEEDED bridge methods resolve to a
// graceful degraded shape ({ success: false, degraded: true }) instead
// of throwing — the never-throws convention at the transport layer.
//
// Auth: the kernel sets a SameSite=Strict console_token cookie when it
// serves this shell's HTML, and the browser attaches it automatically
// (same-origin). No token appears in this file — a cross-origin page can
// load and execute a script without CORS, so an embedded token would leak.
// "credentials": "same-origin" is explicit rather than relying on the fetch
// default.
// Generated ${new Date().toISOString()}.
const KERNEL_BASE = "";
const DEGRADED = Object.freeze({ success: false, degraded: true });
async function kernelInvoke(name, args) {
  const response = await fetch(KERNEL_BASE + "/api/console/" + encodeURIComponent(name), {
    method: "POST",
    headers: { "content-type": "application/json" },
    credentials: "same-origin",
    body: JSON.stringify(args ?? []),
  });
  if (!response.ok) {
    let message = "kernel HTTP " + response.status;
    try { message = (await response.json()).error ?? message; } catch {}
    throw new Error(message);
  }
  return response.json();
}
window.electron = {
  on: (channel, listener) => {
    const source = new EventSource(KERNEL_BASE + "/api/events/" + encodeURIComponent(channel));
    source.onmessage = (e) => {
      try { listener(JSON.parse(e.data)); } catch { listener(e.data); }
    };
    return { close: () => source.close() };
  },
  // Desktop-only window APIs degrade to no-ops in the browser shell.
  isElectron: false,
};
window.hermesAPI = new Proxy({
${methods}
}, {
  get(target, prop) {
    if (prop in target) return target[prop];
    if (typeof prop !== "string" || prop === "then") return undefined;
    // Unseeded bridge method — degrade, never crash (C1 finding:
    // the installer-wizard family probes inspectInstallTarget on
    // mount; the kernel dropped it with the wizard).
    return (...args) => Promise.resolve({ ...DEGRADED, method: prop });
  },
});
`;
}